var updateRuleHomes = flag.Bool("update-rule-homes", false, "rewrite rule_homes_gen.go from the source tree")

// ruleDefinition matches the places a rule ID is minted, not the places one
// is compared or mentioned: a verdict literal or assignment, a ruleID local
// or struct field, the engine's ask helper, and a named rule constant.
var ruleDefinition = regexp.MustCompile(
	`(?:\bRuleID:\s*|\bRuleID\s*=\s*|\bruleID\s*:?=\s*|\bruleID:\s*|\bask\(\s*|\bconst\s+\w*Rule(?:ID)?\s*=\s*)"([A-Za-z0-9][A-Za-z0-9.-]*)"`)

// scanRuleSources walks the production sources that decide verdicts and
// returns every rule ID with the files that mint it, slash-separated and
// relative to the module root.
func scanRuleSources(t *testing.T) map[string][]string {
	t.Helper()
	root := filepath.Join("..", "..")
	found := map[string]map[string]bool{}
	for _, dir := range []string{"internal", filepath.Join("cmd", "guardrail")} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			name := d.Name()
			if d.IsDir() {
				if name == "testdata" {
					return filepath.SkipDir
				}
				return nil
			}
			// Selftest probes name the rule they expect, they do not mint it.
			if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") ||
				strings.HasPrefix(name, "selftest") || name == "rule_homes_gen.go" {
				return nil
			}
			raw, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			rel, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}
			for _, m := range ruleDefinition.FindAllStringSubmatch(string(raw), -1) {
				if found[m[1]] == nil {
					found[m[1]] = map[string]bool{}
				}
				found[m[1]][filepath.ToSlash(rel)] = true
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	out := map[string][]string{}
	for id, files := range found {
		for f := range files {
			out[id] = append(out[id], f)
		}
		sort.Strings(out[id])
	}
	return out
}

func renderRuleHomes(t *testing.T, homes map[string][]string) []byte {
	t.Helper()
	ids := make([]string, 0, len(homes))
	for id := range homes {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b bytes.Buffer
	b.WriteString("// Code generated by `go test ./cmd/guardrail -run TestRuleHomesTableMatchesSource -update-rule-homes`; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("// ruleSourceFiles maps every rule ID the sources mint to the files that\n// mint it (#410). TestRuleHomesTableMatchesSource keeps it current.\n")
	b.WriteString("var ruleSourceFiles = map[string][]string{\n")
	for _, id := range ids {
		b.WriteString("\t" + `"` + id + `": {`)
		for i, f := range homes[id] {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(`"` + f + `"`)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return src
}

// #410: the rule-ID → home table cannot rot. A rule minted in a new place, a
// rule removed, or a rule moved to another file fails here until the table is
// regenerated.
func TestRuleHomesTableMatchesSource(t *testing.T) {
	scanned := scanRuleSources(t)
	want := renderRuleHomes(t, scanned)
	if *updateRuleHomes {
		if err := os.WriteFile("rule_homes_gen.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("rule_homes_gen.go")
	if err != nil {
		t.Fatalf("read rule_homes_gen.go: %v", err)
	}
	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
		t.Fatal("rule_homes_gen.go is stale: run go test ./cmd/guardrail -run TestRuleHomesTableMatchesSource -update-rule-homes")
	}
	// A spot check that the scan sees each way a rule is minted.
	for id, file := range map[string]string{
		"P1.rm-rf":                      "internal/engine/rules_bash.go",             // RuleID: literal
		"P4.secret-path-ambiguous":      "internal/engine/rules_path.go",             // ruleID = assignment
		"P2.gh-repo-delete":             "internal/engine/rules_gh_porcelain.go",     // ruleID: field
		"P4.credential-print":           "internal/engine/rules_credential_print.go", // const
		"ask-allowed-by-operator-grant": "internal/engine/grant.go",                  // const …RuleID
		"operator-action-terminal":      "cmd/guardrail/approval_mode.go",
		"P8.recipe-lint":                "internal/recipe/recipe.go",
	} {
		files := scanned[id]
		if !containsString(files, file) {
			t.Errorf("scan: %s minted in %v, want %s among them", id, files, file)
		}
	}
	if _, ok := scanned["P1.test-deny"]; ok {
		t.Error("scan picked up a test-only rule ID")
	}
}

// #410: every minted rule has a home class; a rule ID with no entry fails.
func TestEveryMintedRuleHasAHomeClass(t *testing.T) {
	for id := range ruleSourceFiles {
		if class := ruleHomeClass(id); class == "" {
			t.Errorf("rule %s has no home class: add it to ruleHomeClasses", id)
		}
	}
	for id := range ruleHomeClasses {
		if _, minted := ruleSourceFiles[id]; !minted {
			t.Errorf("ruleHomeClasses names %s, which no source mints any more", id)
		}
	}
}

func explainHome(t *testing.T, rec audit.Record) string {
	t.Helper()
	path := writeExplainLog(t, rec)
	cwd := rec.RepoRoot
	if cwd == "" {
		cwd = t.TempDir()
	}
	code, out, errOut := runExplain(t, cwd, "--all", "--path", path)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, errOut)
	}
	for _, line := range strings.Split(out, "\n") {
		if strings.HasPrefix(line, "home ") {
			return line
		}
	}
	t.Fatalf("explain printed no home line:\n%s", out)
	return ""
}

func TestExplainPrintsBuiltInRuleHome(t *testing.T) {
	t.Setenv("GUARDRAIL_CONFIG", "")
	home := explainHome(t, audit.Record{TS: "2026-11-15T10:00:00Z", Plane: "claude", Tool: "Bash", Event: "pre", Command: "rm -rf /", Decision: "deny", RuleID: "P1.rm-rf", Reason: "recursive force delete"})
	for _, want := range []string{"base policy", "internal/engine/rules_bash.go"} {
		if !strings.Contains(home, want) {
			t.Errorf("home %q lacks %q", home, want)
		}
	}
}

