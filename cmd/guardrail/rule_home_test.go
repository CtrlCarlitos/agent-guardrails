func TestExplainPrintsTheOriginRuleHomeOfAnEscalation(t *testing.T) {
	t.Setenv("GUARDRAIL_CONFIG", "")
	path := writeExplainLog(t, audit.Record{TS: "2026-11-15T10:00:00Z", Plane: "claude", Tool: "Bash", Event: "pre", Command: "chmod -R 777 /repo", Decision: "deny", RuleID: "host-auto-ask-escalated", OriginRuleID: "P1.chmod", Reason: "the host is running in an auto/bypass permission mode"})
	code, out, errOut := runExplain(t, t.TempDir(), "--all", "--path", path)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, errOut)
	}
	if !strings.Contains(out, "origin") || !strings.Contains(out, "P1.chmod") || !strings.Contains(out, "base policy") {
		t.Errorf("explain does not trace the escalation to its origin rule's home:\n%s", out)
	}
}
